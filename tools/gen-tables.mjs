// Writes kernel/src/tables.rs from data/rules.json, so the kernel and the
// interface read one set of numbers. Run by `npm run kernel`.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const rules = JSON.parse(readFileSync(join(root, "data", "rules.json"), "utf8"));
const list = (values) => `[${values.join(", ")}]`;
const out = `// Generated by tools/gen-tables.mjs from data/rules.json. Do not edit.
// Every number comes from Beijing.exe; data/rules.json names the address.

pub const START_CASH: i64 = ${rules.start.cash};
pub const START_DEBT: i64 = ${rules.start.debt};
pub const START_HEALTH: i64 = ${rules.start.health};
pub const START_FAME: i64 = ${rules.start.fame};
pub const START_DAYS: i64 = ${rules.start.days};
pub const START_CAPACITY: i64 = ${rules.start.capacity};
pub const CAPACITY_MAX: i64 = ${rules.start.capacityMax};
pub const CAPACITY_STEP: i64 = ${rules.start.capacityStep};
pub const DEBT_PERCENT: i64 = ${rules.interest.debtPercent};
pub const DEPOSIT_PERCENT: i64 = ${rules.interest.depositPercent};
pub const STOCKOUT_PICKS: i64 = ${rules.stockout.picks};
pub const STOCKOUT_LAST_DAYS_BELOW: i64 = ${rules.stockout.lastDaysBelow};
pub const MARKET_ROLL: i64 = ${rules.marketRoll};
pub const HEALTH_ROLL: i64 = ${rules.healthRoll};
pub const MONEY_ROLL: i64 = ${rules.moneyRoll};

/// (base, span): price = base + rand() % span.
pub const PRICE: [(i64, i64); 8] = ${list(rules.items.map((item) => `(${item.base}, ${item.span})`))};
/// Fame lost when the item is sold (0 for most).
pub const FAME_ON_SELL: [i64; 8] = ${list(rules.items.map((item) => item.fameOnSell ?? 0))};

/// (n, item, mul, div, add, debt)
pub const MARKET_TABLE: [(i64, usize, i64, i64, i64, i64); ${rules.market.length}] = ${list(
  rules.market.map((e) => `(${e.n}, ${e.item}, ${e.mul}, ${e.div}, ${e.add}, ${e.debt})`),
)};
/// (n, damage)
pub const HEALTH_TABLE: [(i64, i64); ${rules.health.length}] = ${list(rules.health.map((e) => `(${e.n}, ${e.damage})`))};
/// (n, percent, hits_deposit)
pub const MONEY_TABLE: [(i64, i64, bool); ${rules.money.length}] = ${list(
  rules.money.map((e) => `(${e.n}, ${e.percent}, ${e.target === "deposit"})`),
)};

pub const COMA_HEALTH_BELOW: i64 = ${rules.coma.healthBelow};
pub const COMA_DAYS_ABOVE: i64 = ${rules.coma.daysAbove};
pub const COMA_MAX_DAYS: i64 = ${rules.coma.maxDays};
pub const COMA_FEE_BASE: i64 = ${rules.coma.feeBase};
pub const COMA_FEE_SPAN: i64 = ${rules.coma.feeSpan};
pub const COMA_HEAL: i64 = ${rules.coma.heal};
pub const COMA_PLACES: i64 = ${rules.comaPlaces.length};
pub const CRISIS_HEALTH_BELOW: i64 = ${rules.crisis.healthBelow};
pub const BEATING_DEBT_ABOVE: i64 = ${rules.beating.debtAbove};
pub const BEATING_DAMAGE: i64 = ${rules.beating.damage};
pub const HACKER_N: i64 = ${rules.hacker.n};
pub const HACKER_MIN_DEPOSIT: i64 = ${rules.hacker.minDeposit};
pub const HACKER_SMALL_BELOW: i64 = ${rules.hacker.smallBelow};
pub const HACKER_SMALL_DIV: i64 = ${rules.hacker.smallDiv};
pub const HACKER_BIG_DIV: i64 = ${rules.hacker.bigDiv};
pub const HACKER_BIG_DIV_BASE: i64 = ${rules.hacker.bigDivBase};
pub const HACKER_GAIN_MOD: i64 = ${rules.hacker.gainMod};
pub const HOSPITAL_PRICE: i64 = ${rules.hospital.pricePerPoint};
pub const RENT_MIN_CASH: i64 = ${rules.rent.minCash};
pub const RENT_FLAT_QUOTE: i64 = ${rules.rent.flatQuote};
pub const RENT_FLAT_CHARGE: i64 = ${rules.rent.flatCharge};
pub const RENT_CHEAT: i64 = ${rules.rent.cheat};
pub const NET_MIN_CASH: i64 = ${rules.netcafe.minCash};
pub const NET_MAX_VISITS: i64 = ${rules.netcafe.maxVisits};
pub const NET_GAIN_SPAN: i64 = ${rules.netcafe.gainSpan};
pub const TITLES: i64 = ${rules.titles.length};
pub const SCORE_SEEDS: [i64; 10] = ${list(rules.scoreSeeds.map((e) => e.score))};
`;
writeFileSync(join(root, "kernel", "src", "tables.rs"), out);
console.log("kernel/src/tables.rs written");
