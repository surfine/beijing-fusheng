// Builds the kernel: rules.json -> tables.rs -> wasm -> src/kernel/kernel.wasm.ts.
// The wasm is inlined as base64 because an installed app runs in a sandboxed
// frame with an opaque origin and should not depend on fetching its own files.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
execFileSync("node", [join(root, "tools", "gen-tables.mjs")], { stdio: "inherit" });
execFileSync("cargo", ["build", "--release", "--target", "wasm32-unknown-unknown"], {
  cwd: join(root, "kernel"),
  stdio: "inherit",
});
const wasm = readFileSync(join(root, "kernel", "target", "wasm32-unknown-unknown", "release", "beijing_kernel.wasm"));
writeFileSync(
  join(root, "src", "kernel", "kernel.wasm.ts"),
  `// Generated by tools/build-kernel.mjs from kernel/ (${wasm.length} bytes of wasm). Do not edit.\nexport const KERNEL_WASM_BASE64 =\n  "${wasm.toString("base64")}";\n`,
);
console.log(`src/kernel/kernel.wasm.ts written (${wasm.length} bytes)`);
